function setMochaTheme(){

    document.documentElement.style
    .setProperty(
        "--primary",
        "#8b6b4f"
    );

    document.documentElement.style
    .setProperty(
        "--primary-light",
        "#f6eee7"
    );

    document.documentElement.style
    .setProperty(
        "--primary-hover",
        "#eadccf"
    );

    document.documentElement.style
    .setProperty(
        "--primary-border",
        "#e7d8c9"
    );

    document.documentElement.style
    .setProperty(
        "--gradient-start",
        "#c9a07e"
    );

    document.documentElement.style
    .setProperty(
        "--gradient-end",
        "#8b6b4f"
    );

}